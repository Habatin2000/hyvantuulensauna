export const getGalleryImages = (locale: Locale = 'fi'): GalleryImage[] =>
  images.map(({ altEn, altEs, altFr, altDe, captionEn, ...image }) => {
    const localizedAlt: Record<Locale, string> = {
      fi: image.alt,
      en: altEn,
      es: altEs,
      fr: altFr,
      de: altDe,
    };

    return {
      ...image,
      alt: localizedAlt[locale],
      caption: locale === 'en' ? captionEn : image.caption,
    };
  });

export const galleryImages: GalleryImage[] = getGalleryImages('fi');

